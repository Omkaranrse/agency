"""Strongly-typed contracts, schemas, and result models for application agents."""

from enum import StrEnum
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

from agency.domain.entities.design_tokens import DesignTokens
from agency.domain.entities.page_content import PageContent
from agency.domain.entities.qa_report import QAReport
from agency.domain.entities.spec import Spec

# ==============================================================================
# PM Agent Models
# ==============================================================================


class PMSpecResult(BaseModel):
    """Successful PM outcome yielding a validated specification."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    status: Literal["spec"] = "spec"
    spec: Spec
    prompt_version: str
    assumptions: list[str] = Field(default_factory=list)


class PMClarificationResult(BaseModel):
    """PM outcome indicating that critical requirements require clarification."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    status: Literal["clarification"] = "clarification"
    questions: list[str] = Field(min_length=1)
    missing_fields: list[str] = Field(default_factory=list)
    prompt_version: str


PMResult = Annotated[
    PMSpecResult | PMClarificationResult,
    Field(discriminator="status"),
]


class PMOutputSchema(BaseModel):
    """LLM generation contract for PM analysis."""

    model_config = ConfigDict(extra="forbid")

    needs_clarification: bool = False
    clarification_questions: list[str] = Field(default_factory=list)
    missing_fields: list[str] = Field(default_factory=list)
    spec: Spec | None = None
    assumptions: list[str] = Field(default_factory=list)


# ==============================================================================
# Designer Agent Models
# ==============================================================================


class DesignerResult(BaseModel):
    """Validated design tokens and page content generated by DesignerAgent."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    tokens: DesignTokens
    pages: list[PageContent]
    theme: Literal["editorial", "studio"]
    prompt_version: str
    assumptions: list[str] = Field(default_factory=list)


class DesignerOutputSchema(BaseModel):
    """LLM generation contract for visual tokens and page content."""

    model_config = ConfigDict(extra="forbid")

    theme: Literal["editorial", "studio"] = "editorial"
    font_family: str = "Poppins"
    colors: dict[str, str] = Field(min_length=1)
    spacing_scale: dict[str, float] = Field(min_length=1)
    border_radius_scale: dict[str, float] = Field(min_length=1)
    pages: list[PageContent] = Field(min_length=1)
    assumptions: list[str] = Field(default_factory=list)


# ==============================================================================
# Builder Agent Models
# ==============================================================================


class EditCategory(StrEnum):
    """Classification of proposed file modifications."""

    CONTENT = "content"
    TOKENS = "tokens"
    COMPONENT_ESCALATION = "component_escalation"


class FileEditProposal(BaseModel):
    """A proposed file modification vetted by server security policy."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    path: str = Field(min_length=1)
    content: str
    reason: str = Field(min_length=1)
    qa_issue_addressed: str | None = None
    category: EditCategory
    prompt_version: str


class BuilderContext(BaseModel):
    """Input payload providing context for builder file edit generation."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    spec: Spec
    tokens: DesignTokens
    pages: list[PageContent]
    qa_report: QAReport | None = None
    current_revision: int = 1
    manifest: list[str] | None = None
    allow_component_escalation: bool = False
    run_id: str | None = None
    correlation_id: str | None = None


class BuilderResult(BaseModel):
    """List of approved file edit proposals produced by BuilderAgent."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    edits: list[FileEditProposal]
    prompt_version: str
    revision_number: int


class BuilderRawEdit(BaseModel):
    """Unvalidated raw edit proposal received directly from LLM generation."""

    model_config = ConfigDict(extra="forbid")

    path: str
    content: str
    reason: str
    qa_issue_addressed: str | None = None
    category: str = "content"


class BuilderOutputSchema(BaseModel):
    """LLM generation contract for builder edit proposals."""

    model_config = ConfigDict(extra="forbid")

    edits: list[BuilderRawEdit] = Field(default_factory=list)
    explanation: str = ""
