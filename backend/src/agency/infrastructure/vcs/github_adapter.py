"""GitHub adapter implementing the application GitPort."""

import logging
from datetime import UTC, datetime

from agency.application.errors import (
    GitError,
    GitValidationError,
)
from agency.application.ports.git import GitCommitInfo, GitPort, GitRepoInfo
from agency.infrastructure.vcs.config import GitHubSettings, sanitize_repo_name
from agency.infrastructure.vcs.github_client import GitHubClient

logger = logging.getLogger(__name__)

SENSITIVE_FILE_PATTERNS = (
    ".env",
    ".pem",
    ".key",
    "id_rsa",
    "credentials",
    "secret",
    ".sqlite",
    ".db",
)


class GitHubAdapter(GitPort):
    """Adapter bridging application GitPort to GitHub REST API."""

    def __init__(
        self,
        client: GitHubClient,
        settings: GitHubSettings | None = None,
    ) -> None:
        self.client = client
        self.settings = settings or client.settings
        self._cached_owner: str | None = None

    def _resolve_owner(self) -> str:
        """Resolve target GitHub owner/organization."""
        if self._cached_owner:
            return self._cached_owner
        if self.settings.owner:
            self._cached_owner = self.settings.owner
            return self._cached_owner

        user_info = self.client.get_authenticated_user()
        self._cached_owner = str(user_info["login"])
        return self._cached_owner

    def _get_repo_name(self, project_id: str) -> str:
        return sanitize_repo_name(project_id, prefix=self.settings.repo_prefix)

    def _validate_files_for_publication(self, files: dict[str, str | bytes]) -> None:
        """Reject path traversal and sensitive credentials from VCS upload."""
        for path in files:
            clean_path = path.replace("\\", "/")
            if ".." in clean_path or clean_path.startswith("/"):
                raise GitValidationError(
                    f"Unsafe path traversal detected in file: '{path}'"
                )

            lower_path = clean_path.lower()
            for sensitive in SENSITIVE_FILE_PATTERNS:
                if sensitive in lower_path:
                    raise GitValidationError(
                        f"Sensitive file pattern '{sensitive}' disallowed: '{path}'"
                    )

    def init_repository(
        self, project_id: str, default_branch: str = "main"
    ) -> GitRepoInfo:
        """Find or idempotently create a GitHub repository for a project."""
        owner = self._resolve_owner()
        repo_name = self._get_repo_name(project_id)

        # 1. Check if repo already exists
        repo_data = self.client.get_repo(owner, repo_name)
        if repo_data is None:
            # 2. Create repository
            repo_data = self.client.create_repo(
                name=repo_name,
                description=f"Generated website for project {project_id}",
                private=self.settings.private_by_default,
            )

        actual_owner = repo_data.get("owner", {}).get("login", owner)
        repo_url = repo_data.get(
            "html_url", f"https://github.com/{actual_owner}/{repo_name}"
        )

        # 3. Check default branch head
        branch_info = self.client.get_branch(actual_owner, repo_name, default_branch)
        if branch_info is None:
            # Initialize empty repo with initial README commit
            initial_tree = self.client.create_tree(
                actual_owner,
                repo_name,
                base_tree_sha=None,
                files={"README.md": f"# {repo_name}\n\nGenerated by Agency AI.\n"},
            )
            initial_commit = self.client.create_commit(
                actual_owner,
                repo_name,
                message="Initial repository commit",
                tree_sha=initial_tree,
                parents=[],
                author_name="Agency System",
            )
            # Create default branch ref
            self.client.create_ref(
                actual_owner, repo_name, default_branch, initial_commit
            )
            current_sha = initial_commit
        else:
            current_sha = str(branch_info["commit"]["sha"])

        return GitRepoInfo(
            project_id=project_id,
            default_branch=default_branch,
            current_commit=current_sha,
            branches=[default_branch],
            repo_name=repo_name,
            repo_url=repo_url,
            owner=actual_owner,
        )

    def create_branch(
        self, project_id: str, branch_name: str, base_branch: str | None = None
    ) -> None:
        """Create a new branch pointer from base branch."""
        owner = self._resolve_owner()
        repo_name = self._get_repo_name(project_id)
        base = base_branch or "main"

        base_info = self.client.get_branch(owner, repo_name, base)
        if not base_info:
            raise GitError(f"Base branch '{base}' not found in repo '{repo_name}'.")

        base_sha = str(base_info["commit"]["sha"])
        self.client.create_ref(owner, repo_name, branch_name, base_sha)

    def commit_changes(
        self,
        project_id: str,
        message: str,
        branch: str = "main",
        author: str = "Agency AI",
        files: dict[str, str | bytes] | None = None,
    ) -> GitCommitInfo:
        """Record atomic tree commit containing the approved source files."""
        owner = self._resolve_owner()
        repo_name = self._get_repo_name(project_id)

        # 1. Fetch current branch head
        branch_info = self.client.get_branch(owner, repo_name, branch)
        if not branch_info:
            raise GitError(f"Branch '{branch}' not found in repo '{repo_name}'.")

        parent_sha = str(branch_info["commit"]["sha"])
        parent_tree = str(branch_info["commit"]["commit"]["tree"]["sha"])

        # 2. Validate files if present
        payload_files = files or {}
        if payload_files:
            self._validate_files_for_publication(payload_files)

        # 3. Create tree
        tree_sha = self.client.create_tree(
            owner,
            repo_name,
            base_tree_sha=parent_tree,
            files=payload_files,
        )

        # 4. Create commit
        commit_sha = self.client.create_commit(
            owner,
            repo_name,
            message=message,
            tree_sha=tree_sha,
            parents=[parent_sha],
            author_name=author,
        )

        # 5. Advance branch reference
        self.client.update_ref(owner, repo_name, branch, commit_sha)

        return GitCommitInfo(
            commit_sha=commit_sha,
            branch=branch,
            message=message,
            author=author,
            committed_at=datetime.now(UTC),
        )

    def get_commit_info(self, project_id: str, commit_sha: str) -> GitCommitInfo:
        """Retrieve commit details by SHA."""
        owner = self._resolve_owner()
        repo_name = self._get_repo_name(project_id)

        data = self.client.get_commit(owner, repo_name, commit_sha)
        commit_obj = data["commit"]
        author_info = commit_obj.get("author", {})

        date_str = author_info.get("date")
        committed_at = (
            datetime.fromisoformat(date_str) if date_str else datetime.now(UTC)
        )

        return GitCommitInfo(
            commit_sha=str(data["sha"]),
            branch="main",
            message=str(commit_obj.get("message", "")),
            author=str(author_info.get("name", "Agency AI")),
            committed_at=committed_at,
        )

    def get_repo_info(self, project_id: str) -> GitRepoInfo:
        """Retrieve repository metadata."""
        owner = self._resolve_owner()
        repo_name = self._get_repo_name(project_id)

        repo_data = self.client.get_repo(owner, repo_name)
        if not repo_data:
            raise GitError(f"Repository '{owner}/{repo_name}' not found.")

        default_branch = str(repo_data.get("default_branch", "main"))
        branch_info = self.client.get_branch(owner, repo_name, default_branch)
        current_sha = (
            str(branch_info["commit"]["sha"])
            if branch_info
            else "0000000000000000000000000000000000000000"
        )

        actual_owner = repo_data.get("owner", {}).get("login", owner)
        return GitRepoInfo(
            project_id=project_id,
            default_branch=default_branch,
            current_commit=current_sha,
            branches=[default_branch],
            repo_name=repo_name,
            repo_url=str(repo_data.get("html_url", "")),
            owner=actual_owner,
        )
